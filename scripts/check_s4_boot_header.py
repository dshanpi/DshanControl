#!/usr/bin/env python3
"""Reject missing/mismatched vendor Boot0 hardware info in the FINAL Tina image.

This gate complements the full package audit; it does not establish board support.
Expected bytes must come from update_chip with the selected S4 buildserver config,
never from another board's Boot0 or an edited OP-TEE binary.
"""
import argparse
import hashlib
import json
import struct
from pathlib import Path


def check_boot0(data, expected):
    if len(expected) != 5 or expected[:3] != b'RAW':
        raise ValueError('expected hardware information must be five vendor-generated bytes')
    if len(data) < 0x100 or data[4:12] != b'eGON.BT0':
        raise ValueError('invalid Boot0 header')
    length = struct.unpack_from('<I', data, 16)[0]
    if length != len(data) or length % 4:
        raise ValueError('invalid Boot0 length')
    if data[0xf1:0xf6] != expected:
        raise ValueError('Boot0 hardware information missing or mismatched: update_chip/buildserver failed')
    words = list(struct.unpack('<%dI' % (length // 4), data))
    checksum = words[3]
    words[3] = 0x5f0a6c39
    if sum(words) & 0xffffffff != checksum:
        raise ValueError('Boot0 checksum mismatch')
    return {'sha256': hashlib.sha256(data).hexdigest(), 'hardware_info': expected.hex()}


def check_image(path, expected):
    with Path(path).open('rb') as stream:
        size = stream.seek(0, 2)
        stream.seek(0)
        header = stream.read(1024)
        if len(header) != 1024 or header[:8] != b'IMAGEWTY':
            raise ValueError('expected a Tina IMAGEWTY vendor package')
        if struct.unpack_from('<II', header, 8) != (0x300, 96):
            raise ValueError('unsupported container header')
        if struct.unpack_from('<Q', header, 24)[0] != size:
            raise ValueError('container size mismatch')
        stride, count, offset = struct.unpack_from('<III', header, 56)
        if stride != 1024 or not 0 < count < 1024 or offset != 1024:
            raise ValueError('invalid container table')
        end = offset + count * stride
        results = {}
        for i in range(count):
            stream.seek(offset + i * stride)
            entry = stream.read(stride)
            if len(entry) != stride or struct.unpack_from('<II', entry) != (0x100, 1024):
                raise ValueError('invalid container entry')
            name = entry[36:292].split(b'\0')[0].decode('ascii')
            stored, length, start = struct.unpack_from('<QQQ', entry, 292)
            if not 0 < length <= stored or start < end or start % 1024 or start + stored > size:
                raise ValueError('invalid payload bounds')
            end = start + stored
            if name in ('boot0_sdcard.fex', 'boot0_nand.fex'):
                if name in results or length > 1024 * 1024:
                    raise ValueError('duplicate or oversized Boot0')
                stream.seek(start)
                results[name] = check_boot0(stream.read(length), expected)
        if 'boot0_sdcard.fex' not in results:
            raise ValueError('SD NAND Boot0 missing')
    return results


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('image', type=Path)
    parser.add_argument('--expected-hardware-info', required=True,
                        help='five bytes in hex from the selected vendor update_chip output')
    args = parser.parse_args()
    try:
        result = check_image(args.image, bytes.fromhex(args.expected_hardware_info))
    except (ValueError, OSError, struct.error) as error:
        parser.exit(1, 'Boot0 gate rejected image: %s\n' % error)
    print(json.dumps(result, indent=2))


if __name__ == '__main__':
    main()
